import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

async function readFileIfExists(filePath) {
  try {
    return await fs.readFile(filePath, "utf8");
  } catch (err) {
    if (err && err.code === "ENOENT") return null;
    throw err;
  }
}

async function main() {
  const scriptDir = path.dirname(fileURLToPath(import.meta.url));
  const repoRoot = scriptDir;
  const sourcePath = path.join(repoRoot, "content-ops-codex-pack", ".env");
  const destPath = path.join(repoRoot, "content-ops-codex-pack", "apps", "web", ".env.local");

  const source = await readFileIfExists(sourcePath);
  if (source === null) {
    console.error(`Missing source env file: ${sourcePath}`);
    process.exit(1);
  }

  const header =
    "# Auto-generated from content-ops-codex-pack/.env\n" +
    "# Do not edit this file directly; edit the source .env and re-run: npm run sync:env\n\n";

  const normalizedSource = source.endsWith("\n") ? source : `${source}\n`;
  const nextContent = `${header}${normalizedSource}`;

  const current = await readFileIfExists(destPath);
  if (current === nextContent) {
    console.log("Env already in sync:", destPath);
    return;
  }

  await fs.mkdir(path.dirname(destPath), { recursive: true });
  await fs.writeFile(destPath, nextContent, "utf8");
  console.log("Synced env to:", destPath);
}

await main();
